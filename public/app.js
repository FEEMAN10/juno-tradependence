function loadInvitation(){
  sb.rpc('get_invitation',{p_token:currentToken()}).then(function(res){
    var row=(res && res.data && res.data[0])||null;
    if(!row) return;
    if(row.guest_name){document.getElementById('topGuest').textContent=row.guest_name;document.getElementById('dearGuest').textContent=row.guest_name;}
    if(row.main_course){                    // already submitted -> show the locked, final state
      STATE.rsvp='accept';STATE.main=row.main_course;STATE.dessert=row.dessert;STATE.bev=row.beverage;
      STATE.diet=row.dietary_flag?'Yes':'No';STATE.dietText=row.dietary_note||'';
      document.getElementById('rsvpBlock').style.display='none';
      document.getElementById('rsvpState').classList.add('show');refreshRsvpText();
      showDone();
    } else if(row.rsvp_status==='accepted'){ reflectRsvp('accept'); }
      else if(row.rsvp_status==='declined'){ reflectRsvp('decline'); }
  }).catch(function(){});
}
function reflectRsvp(v){                     // show a saved RSVP without re-writing it to the server
  STATE.rsvp=v;
  document.getElementById('rsvpBlock').style.display='none';
  document.getElementById('rsvpState').classList.add('show');
  document.getElementById('mealLock').classList.toggle('gone',v==='accept');
  if(v==='accept') showShare(); else hideShare();
  refreshRsvpText();
}

